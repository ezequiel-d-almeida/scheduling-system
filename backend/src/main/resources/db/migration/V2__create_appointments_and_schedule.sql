CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE availability_windows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_of_week INTEGER NOT NULL CHECK (day_of_week BETWEEN 0 AND 6),
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_availability_window CHECK (start_time < end_time)
);

CREATE TABLE schedule_blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    reason VARCHAR(200),
    CONSTRAINT chk_schedule_block_interval CHECK (starts_at < ends_at)
);

CREATE TABLE appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT NOT NULL REFERENCES services(id),
    client_name VARCHAR(120) NOT NULL,
    client_phone VARCHAR(40) NOT NULL,
    modality VARCHAR(20) NOT NULL CHECK (modality IN ('IN_PERSON', 'REMOTE')),
    location VARCHAR(200),
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED')),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT chk_appointment_interval CHECK (starts_at < ends_at)
);
CREATE INDEX idx_appointments_starts_at ON appointments(starts_at);
CREATE INDEX idx_appointments_status_starts_at ON appointments(status, starts_at);
ALTER TABLE appointments ADD CONSTRAINT appointments_no_active_overlap
EXCLUDE USING gist (tstzrange(starts_at, ends_at, '[)') WITH &&)
WHERE (status IN ('PENDING', 'CONFIRMED'));

CREATE TABLE appointment_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL REFERENCES appointments(id),
    event_type VARCHAR(30) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_appointment_events_appointment ON appointment_events(appointment_id, occurred_at);
